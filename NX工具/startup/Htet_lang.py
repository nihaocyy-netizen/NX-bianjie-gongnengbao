def _system_ui_lang():
    try:
        import ctypes
        lcid = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        primary = lcid & 0x03FF
        sub = (lcid >> 10) & 0x3F
        if primary == 0x04:
            return "zh_tw" if sub in (0x01, 0x03, 0x05) else "zh_cn"
    except Exception:
        pass
    return "en"


_ZH_CN_ALIASES = frozenset((
    "simpl_chinese", "simplified_chinese", "zh_cn", "zh-cn", "chs",
    "schinese", "zh_hans",
))
_ZH_TW_ALIASES = frozenset((
    "trad_chinese", "traditional_chinese", "zh_tw", "zh-tw", "cht",
    "chinese", "zh_hant",
))


def detect_lang():
    value = (os.environ.get("UGII_LANG") or "").strip().lower()
    # 精确成员判断：chinese 不能吞掉 simpl_chinese / trad_chinese
    if value in _ZH_CN_ALIASES:
        return "zh_cn"
    if value in _ZH_TW_ALIASES:
        return "zh_tw"
    if value:
        return "en"
    return _system_ui_lang()


LANG = detect_lang()


def T(key, *args):
    text = (MSG.get(LANG) or {}).get(key)
    if text is None:
        text = MSG["en"].get(key, key)
    if args:
        return text.format(*args)
    return text


def render_ps(template):
    merged = dict(MSG["en"])
    merged.update(MSG.get(LANG) or {})
    for key, value in merged.items():
        template = template.replace("[[%s]]" % key, str(value))
    return template
